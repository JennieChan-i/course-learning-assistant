def main():
    target = ROOT / "data" / "sample_courses.csv"
    target.parent.mkdir(exist_ok=True)
    with target.open("w", encoding="utf-8-sig", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(
            [
                "chunk_id",
                "chunk_text",
                "doc_id",
                "doc_name",
                "topic",
                "subtopic",
                "content_type",
                "suitable_questions",
                "chunk_order",
            ]
        )
        n = 0
        for doc_id, name, lessons in LESSONS:
            for order, (topic, text, questions) in enumerate(lessons, 1):
                n += 1
                writer.writerow(
                    [f"S{n:02d}", text, doc_id, name, name, topic, "概念与应用", questions, str(order)]
                )
    print(f"Created {n} original sample chunks.")


if __name__ == "__main__":
    main()
